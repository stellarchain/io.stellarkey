#!/usr/bin/env node
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const circuitsDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const buildDir = join(circuitsDir, 'build');
const vkPath = join(buildDir, 'verification_key.json');

if (!existsSync(vkPath)) {
  console.error(`Verification key not found at ${vkPath}. Run setup:dev first.`);
  process.exit(1);
}

const vk = JSON.parse(readFileSync(vkPath, 'utf8'));

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest();
}

function rustByteArray(bytes) {
  const values = [...bytes].map((byte) => `0x${byte.toString(16).padStart(2, '0')}`);
  const lines = [];
  for (let offset = 0; offset < values.length; offset += 16) {
    lines.push(`    ${values.slice(offset, offset + 16).join(', ')},`);
  }
  return `[\n${lines.join('\n')}\n]`;
}

function fieldToBytes(str) {
  const hex = BigInt(str).toString(16).padStart(64, '0');
  return Buffer.from(hex, 'hex');
}

function g1ToBytes(p) {
  return Buffer.concat([fieldToBytes(p[0]), fieldToBytes(p[1])]);
}

function g2ToBytes(p) {
  // SnarkJS G2 format is [[x.c0, x.c1], [y.c0, y.c1]]
  // Soroban CAP-0074 format is x.c1, x.c0, y.c1, y.c0
  return Buffer.concat([
    fieldToBytes(p[0][1]),
    fieldToBytes(p[0][0]),
    fieldToBytes(p[1][1]),
    fieldToBytes(p[1][0]),
  ]);
}

const alphaG1 = g1ToBytes(vk.vk_alpha_1);
const betaG2 = g2ToBytes(vk.vk_beta_2);
const gammaG2 = g2ToBytes(vk.vk_gamma_2);
const deltaG2 = g2ToBytes(vk.vk_delta_2);

const icLenBuf = Buffer.alloc(4);
icLenBuf.writeUInt32BE(vk.IC.length, 0);

const icBufs = vk.IC.map(g1ToBytes);

const binVk = Buffer.concat([
  alphaG1,
  betaG2,
  gammaG2,
  deltaG2,
  icLenBuf,
  ...icBufs,
]);

console.log(`Exported verifying-key.bin (${binVk.length} bytes, IC count: ${vk.IC.length})`);
writeFileSync(join(buildDir, 'verifying-key.bin'), binVk);
writeFileSync(join(buildDir, 'action-vk.json'), JSON.stringify(vk, null, 2));
copyFileSync(
  join(buildDir, 'verifying-key.bin'),
  join(circuitsDir, '../crates/verifier/src/verifying_key.bin'),
);
const poseidonParameterHash = sha256(
  readFileSync(join(circuitsDir, '../parameters/poseidon2-bn254-t4-v1.json')),
);
const circuitHash = sha256(readFileSync(join(buildDir, 'action.r1cs')));
const verificationKeyHash = sha256(binVk);
writeFileSync(
  join(circuitsDir, '../contracts/pool/src/generated_artifacts.rs'),
  `// Generated by circuits/scripts/export-verifier-artifacts.mjs. Do not edit.\n\
pub const EXPECTED_POSEIDON2_PARAMETER_HASH: [u8; 32] = ${rustByteArray(poseidonParameterHash)};\n\
pub const EXPECTED_CIRCUIT_HASH: [u8; 32] = ${rustByteArray(circuitHash)};\n\
pub const EXPECTED_VERIFICATION_KEY_HASH: [u8; 32] = ${rustByteArray(verificationKeyHash)};\n`,
);

console.log('✓ Verification key artifacts exported, embedded, and hash-pinned successfully.');
